#!/usr/bin/env python3
"""Generate the filming scenario of a knocked-down person on a slope and at a wall: scripts/bench/ragdoll-brace-places.bench.

    python3 reports/physics/2026-11-14-fall-bracing/places_bench.py

The pair of `look_bench.py` at two places. The victim stands between the hero's first spot and the attacker, who is
`near` in front of the hero, and falls against the hero's first facing: `face uphill` makes it a fall downhill, a hero
with his back to a wall a fall into it. Each fall is filmed twice from its side, the second time slowed three times.
Run it with RAGDOLL_BRACE=0 OPENGOTHIC_BRACE_MEASURE=1 and with RAGDOLL_BRACE=1 and pair the takes by name.
"""
import math
from pathlib import Path

from look_bench import ATTACKER, GAP, ROOT, TARGET

FAR = 350.0  # the hero from the attacker once the pair stands
SLOPE = "goto NW_FARM1_OUT_07"  # an open grass slope of 16.5 degrees above Lobart's farm
# A plank hut of the harbour quarter (the second `clear` of a cell takes its townsfolk out of the shot): the corner probe puts the hero 188 cm in front of its wall, facing it;
# one metre nearer he stands 88 cm from it.
WALL = "goto NW_CITY_MERCHANT_TRADE_04\nwait 500\ncorner left go 1\ngoto pos 3271.3 -128 -4806.4"


def head(seed: int, spot: str, face: str, near: float) -> str:
    return f"""
seed {seed}
release all
watch player
clear 3000
{spot}
wait 500
clear 3000
{face}
arc {ATTACKER} 1 {near:.0f} 0
freeze {ATTACKER}
knockdown-launch-equip
arc {TARGET} 1 1000 0
freeze {TARGET}
stats npc {TARGET} hpmax 100000 hp 100000
wait 600
"""


def tail(take: str, angle: int, slow: bool, hold: bool = False) -> str:
    """hold: the frame stays where it is, so a body turned by the wall does not swing the camera round."""
    return f"""watch {TARGET}
cam follow 430 110 {angle}
wait 1200{chr(10) + "cam hold" if hold else ""}
{"slowmo 3" if slow else "slowmo 1"}
rec {take}{"-slow" if slow else ""}
wait 400
ani {ATTACKER} T_2HATTACKL
wait 100
stun {TARGET} posture
strike {TARGET} {ATTACKER}
wait 4500
stop
slowmo 1
watch player
clear 3000
"""


def axis(seed: int, take: str, spot: str, face: str, fall: str, angle: int, near: float, slow: bool,
         hold: bool = False) -> str:
    """fall: back, forward or side, as on the flat; the hero ends behind, in front of or beside the attacker."""
    side = (FAR * FAR + GAP * GAP) ** 0.5
    place, dist, at = {"back": (180, FAR + GAP, 0.0), "forward": (0, FAR - GAP, 0.0),
                       "side": (90, side, math.degrees(math.atan(GAP / FAR)))}[fall]
    return head(seed, spot, face, near) + f"""watch {ATTACKER}
place {FAR:.0f} {place}
put {TARGET} {dist:.1f} {at:.2f}
""" + tail(take, angle, slow, hold)


def to_wall_forward(seed: int, take: str, angle: int, slow: bool, step: float = 60.0) -> str:
    """The victim stands `step` in front of the hero and faces the wall behind him, the attacker behind the victim;
    the hero steps aside and the victim falls forward into the wall."""
    return head(seed, WALL, "turn 180", 600) + f"""put {TARGET} {step:.0f} 0
place {step + GAP:.0f} 0 {ATTACKER}
freeze {ATTACKER}
watch {TARGET}
place {FAR:.0f} 90
""" + tail(take, angle, slow, True)


def generate() -> str:
    text = """# Generated by reports/physics/2026-11-14-fall-bracing/places_bench.py.
# A posture knockdown on a slope and at a wall, filmed for the eye from the side of the fall, then slowed.
# @timeout 1500
cheat god
set time 12 0
release all
overlay off
ragdoll on
"""
    seed = 92100
    for slow in (False, True):
        text += axis(seed, "slope-down-back", SLOPE, "face uphill", "back", 270, 120, slow)
        text += axis(seed + 1, "slope-down-forward", SLOPE, "face uphill", "forward", 270, 120, slow)
        text += axis(seed + 2, "slope-up-forward", SLOPE, "face downhill", "forward", 270, 120, slow)
        text += axis(seed + 3, "slope-down-side", SLOPE, "face uphill", "side", 180, 120, slow)
        text += axis(seed + 4, "wall-back", WALL, "turn 180", "back", 90, 60, slow, True)
        text += to_wall_forward(seed + 5, "wall-forward", 270, slow)
        seed += 6
    return text + "\nquit\n"


if __name__ == "__main__":
    out = ROOT / "scripts" / "bench" / "ragdoll-brace-places.bench"
    out.write_text(generate())
    print(out, generate().count("\nrec "), "takes")
