#!/usr/bin/env python3
"""Generate the filming scenario of a knocked-down person falling four ways: scripts/bench/ragdoll-brace-look.bench.

    python3 reports/physics/2026-11-14-fall-bracing/look_bench.py

A pair of mercenaries on the open field of the animation look benches; the victim is stunned by posture and struck,
so it falls away from the attacker. The victim always faces the hero, the attacker stands in front of it, behind
it or at a side: the fall goes backward, forward or sideways. Each fall is filmed from the side of the fall and
from three quarters, the side view once more slowed three times. Run the same scenario on the game before and
after a change (RAGDOLL_BRACE=0 and 1 once the flag exists) and pair the takes by name.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
ATTACKER, TARGET = "SLD_826_SOELDNER", "SLD_815_SOELDNER"
GAP = 40.0  # cm between the pair
FAR = 500.0  # the hero from the attacker: out of the shot, on the open field

# name: where the hero stands round the attacker (`place` angle), how far and at what angle the victim is put
# from the hero, the camera angles round the victim: along the fall's side, three quarters.
side = (FAR * FAR + GAP * GAP) ** 0.5
tilt = 4.5739  # atan(GAP / FAR), degrees
FALLS = {
    "back": (180, FAR + GAP, 0.0, (270, 315)),
    "forward": (0, FAR - GAP, 0.0, (270, 225)),
    "side-a": (90, side, tilt, (0, 45)),
    "side-b": (90, side, -tilt, (0, 315)),
}


def cell(seed: int, name: str, view: str, angle: int, slow: bool) -> str:
    place, dist, at, _ = FALLS[name]
    take = f"{name}-{view}" + ("-slow" if slow else "")
    return f"""
seed {seed}
release all
watch player
clear 3000
goto NW_BIGFARM_VORPOSTEN1_01_RIGHTFIELD_02
wait 500
arc {ATTACKER} 1 600 0
freeze {ATTACKER}
knockdown-launch-equip
arc {TARGET} 1 1000 0
freeze {TARGET}
stats npc {TARGET} hpmax 100000 hp 100000
wait 600
watch {ATTACKER}
place {FAR:.0f} {place}
put {TARGET} {dist:.1f} {at:.2f}
watch {TARGET}
cam follow 430 110 {angle}
wait 1200
{"slowmo 3" if slow else "slowmo 1"}
rec {take}
wait 400
ani {ATTACKER} T_2HATTACKL
wait 100
stun {TARGET} posture
strike {TARGET} {ATTACKER}
wait 4500
stop
slowmo 1
watch player
clear 3000
"""


def generate() -> str:
    text = """# Generated by reports/physics/2026-11-14-fall-bracing/look_bench.py.
# A posture knockdown four ways on flat ground, filmed for the eye: side of the fall, three quarters, slowed side.
# @timeout 900
cheat god
set time 12 0
release all
overlay off
ragdoll on
"""
    seed = 91000
    for name, (_, _, _, (main, quarter)) in FALLS.items():
        for view, angle, slow in (("side", main, False), ("q", quarter, False), ("side", main, True)):
            text += cell(seed, name, view, angle, slow)
            seed += 1
    return text + "\nquit\n"


if __name__ == "__main__":
    out = ROOT / "scripts" / "bench" / "ragdoll-brace-look.bench"
    out.write_text(generate())
    print(out, generate().count("\nrec "), "takes")
