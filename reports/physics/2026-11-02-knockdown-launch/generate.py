#!/usr/bin/env python3
"""Generate the paired native knockdown and isolated posture-stun fixture."""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
ATTACKER = "SLD_826_SOELDNER"
TARGET = "SLD_815_SOELDNER"


def preparation(seed):
    return f"""seed {seed}
release all
watch player
clear 3000
goto NW_BIGFARM_VORPOSTEN1_01_RIGHTFIELD_02
wait 500
clear 3000
corner right go 0
clear 3000
turn 180
arc {ATTACKER} 1 600 0
freeze {ATTACKER}
knockdown-launch-equip
arc {TARGET} 1 1000 0
freeze {TARGET}
stats npc {TARGET} hpmax 100000 hp 100000
wait 600
watch {ATTACKER}
"""


def generate():
    text = """# Generated by reports/physics/2026-11-02-knockdown-launch/generate.py.
# The npc-probe setup, exact axe and 100 ms attack age; no diagnostic trace flags.
# Interleaved close/medium/far cells, 20 each, followed by 10 isolated drift probes.
cheat god
set time 12 0
release all
overlay off
ragdoll on
"""
    for index in range(20):
        for cell, low, high, seed in (
            ("close", 30, 40, 83000 + 2 * index),
            ("medium", 50, 90, 84000 + index),
            ("far", 100, 170, 83001 + 2 * index),
        ):
            distance = f"{low + (high - low) * index / 19:.1f}"
            text += "\n" + preparation(seed)
            text += f"""rec birth-{cell}-seed-{seed}-distance-{distance} novideo
ani {ATTACKER} T_2HATTACKL
wait 100
place 1000 180
put {TARGET} {1000 + float(distance):.1f} 0
stun {TARGET} posture
strike {TARGET} {ATTACKER}
wait 900
stop
watch player
clear 3000
"""
    text += drift_probes()
    return text + "\nquit\n"


def drift_probes():
    text = ""
    for index in range(5):
        for group, seed in (("flat", 85000 + 2 * index), ("duel-slope", 85001 + 2 * index)):
            text += "\n" + preparation(seed)
            if group == "flat":
                # Keep the old target point, but put the actual stun source 120 cm away.
                text += f"""place 1000 180
put {TARGET} 1120 0
watch {TARGET}
place 120 0
put {ATTACKER} 4000 90
"""
            else:
                text += f"""put-at player 65184.6 2315.5 -12179
wait 200
put {ATTACKER} 4000 90
put-at {TARGET} 65138.5 2379.98 -12072.3
"""
            text += f"""watch player
rec drift-{group}-seed-{seed} novideo
freeze {TARGET} off
stun-drift {TARGET} player
stun {TARGET} posture
wait 1700
stop
clear 3000
"""
    return text


if __name__ == "__main__":
    destination = ROOT / "scripts/bench/knockdown-launch.bench"
    destination.write_text(generate())
    print(destination.relative_to(ROOT))
    drift = ROOT / "scripts/bench/knockdown-drift.bench"
    drift.write_text("# Generated by reports/physics/2026-11-02-knockdown-launch/generate.py.\n"
                     "# Five flat and five duel-slope posture stuns; no knockdowns.\n"
                     "cheat god\nset time 12 0\nrelease all\noverlay off\nragdoll on\n" +
                     drift_probes() + "\nquit\n")
    print(drift.relative_to(ROOT))
